"""Renders data/seer.svg into the app icon files.

    python3 tools/make_icon.py

writes data/seer.ico (Windows resource, 16-256 px), data/seer.png (256 px) and
icons/app_icon.h (the .ico as a C array, for the Linux window icon). Needs
Pillow. The rasterizer handles what seer.svg uses: one rounded <rect> and one
<path> of absolute M/L/H/V/C/Z commands.
"""
import re, sys, pathlib
from PIL import Image, ImageDraw

root = pathlib.Path(__file__).resolve().parent.parent
svg = (root / "data/seer.svg").read_text()

view = float(re.search(r'viewBox="0 0 ([\d.]+)', svg).group(1))
rect = re.search(r'<rect[^>]*rx="([\d.]+)"[^>]*fill="(#[0-9A-Fa-f]{6})"', svg)
path = re.search(r'<path d="([^"]+)"[^>]*fill="(\w+)"', svg)

def path_points(d, steps=24):
    toks = re.findall(r'[MLHVCZ]|-?[\d.]+', d)
    pts, i, cmd, x, y = [], 0, None, 0.0, 0.0
    def num():
        nonlocal i
        i += 1
        return float(toks[i - 1])
    while i < len(toks):
        if toks[i].isalpha():
            cmd = toks[i]; i += 1
            if cmd == 'Z': continue
        if cmd == 'M' or cmd == 'L': x, y = num(), num(); pts.append((x, y))
        elif cmd == 'H': x = num(); pts.append((x, y))
        elif cmd == 'V': y = num(); pts.append((x, y))
        elif cmd == 'C':
            x1, y1, x2, y2, x3, y3 = (num() for _ in range(6))
            for s in range(1, steps + 1):
                t = s / steps; u = 1 - t
                pts.append((u*u*u*x + 3*u*u*t*x1 + 3*u*t*t*x2 + t*t*t*x3,
                            u*u*u*y + 3*u*u*t*y1 + 3*u*t*t*y2 + t*t*t*y3))
            x, y = x3, y3
        else: sys.exit(f"unsupported path command {cmd}")
    return pts

big = 2048
k = big / view
img = Image.new("RGBA", (big, big), (0, 0, 0, 0))
draw = ImageDraw.Draw(img)
draw.rounded_rectangle([0, 0, big - 1, big - 1], radius=float(rect.group(1)) * k, fill=rect.group(2))
fill = {"white": "#FFFFFF"}.get(path.group(2), path.group(2))
draw.polygon([(px * k, py * k) for px, py in path_points(path.group(1))], fill=fill)

sizes = [16, 24, 32, 48, 64, 128, 256]
frames = [img.resize((s, s), Image.LANCZOS) for s in sizes]
frames[-1].save(root / "data/seer.png")
frames[-1].save(root / "data/seer.ico", sizes=[(s, s) for s in sizes], append_images=frames[:-1])

ico = (root / "data/seer.ico").read_bytes()
lines = [", ".join(f"0x{b:02x}" for b in ico[i:i + 16]) for i in range(0, len(ico), 16)]
(root / "icons/app_icon.h").write_text(
    "// Generated by tools/make_icon.py from data/seer.svg; do not edit.\n"
    "// data/seer.ico, the Linux window icon.\n\n"
    "read_only global U8 seer_app_icon_ico__data[] =\n{\n  " + ",\n  ".join(lines) + ",\n};\n"
    "read_only global String8 seer_app_icon_ico = {seer_app_icon_ico__data, sizeof(seer_app_icon_ico__data)};\n")
print(f"data/seer.ico {len(ico)} bytes, sizes {sizes}")
